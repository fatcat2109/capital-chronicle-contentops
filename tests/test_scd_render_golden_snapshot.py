@pytest.mark.parametrize("fixture,validator_key,expected", FIXTURE_CASES)
def test_fixture_validation_state(fixture, validator_key, expected):
    payload = load(fixture)
    validator = RENDER_GOLDEN_SNAPSHOT_VALIDATORS[validator_key]
    result = validator(payload)
    assert result["validation_state"] == expected, (fixture, result)


