def test_all_four_replay_states_have_pass_golden_snapshot():
    states = set()
    for name in ("golden_snapshot_pass.json", "golden_snapshot_blocked_state.json",
                 "golden_snapshot_review_required_state.json", "golden_snapshot_unknown_state.json"):
        snap = load(name)
