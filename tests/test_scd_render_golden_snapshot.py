def test_module_source_has_no_runtime_or_network_patterns():
    src_path = os.path.join(os.path.dirname(__file__), "..",
                            "live_contentops", "scd_render_golden_snapshot.py")
    with open(src_path, encoding="utf-8") as f:
        src = f.read()
    forbidden = [
        "import requests", "import urllib", "import socket", "import httpx",
        "import openai", "import anthropic", "os.environ", "getenv", "dotenv",
        ".post(", "fetch(", "document.querySelector", "window.",
        "addEventListener", "innerHTML", "<script", "playwright", "selenium",
        "sendMessage", "chat_id", "webhook",
    ]
    hits = [p for p in forbidden if p in src]
    assert hits == [], hits
