# --- Helper: compare ---

def test_compare_matching_spec_is_pass():
    spec = _render_spec("PASS", "rs_cmp")
    snap = freeze_render_golden_snapshot(spec, "PASS")
    result = compare_render_spec_to_golden_snapshot(spec, snap)
    assert result["canonical_json_match"] is True
    assert result["structural_binding_match"] is True
    assert result["mutation_detected"] is False
    assert validate_render_binding_conformance_result(result)["validation_state"] == "PASS"


def test_compare_detects_mutation_after_freeze():
    spec = _render_spec("PASS", "rs_cmp")
    snap = freeze_render_golden_snapshot(spec, "PASS")
    snap["snapshot_payload"]["view_model_id"] = "vm_tampered"
    result = compare_render_spec_to_golden_snapshot(spec, snap)
    assert result["mutation_detected"] is True
    assert validate_render_binding_conformance_result(result)["validation_state"] == "BLOCKED"


def test_compare_detects_structural_divergence():
    spec = _render_spec("PASS", "rs_cmp")
    snap = freeze_render_golden_snapshot(spec, "PASS")
    altered = copy.deepcopy(spec)
    altered["layout_regions"] = ["command_hero"]
    result = compare_render_spec_to_golden_snapshot(altered, snap)
    assert result["missing_regions"]
    assert result["structural_binding_match"] is False
    assert validate_render_binding_conformance_result(result)["validation_state"] == "BLOCKED"


# --- Helper: manifest / report ---

def _all_state_snapshots():
    return [freeze_render_golden_snapshot(_render_spec(s, "rs_" + s.lower()), s)
            for s in ("PASS", "BLOCKED", "REVIEW_REQUIRED", "UNKNOWN")]


def test_manifest_requires_all_four_states():
    full = build_golden_snapshot_manifest(_all_state_snapshots(), "v1")
    assert validate_render_golden_snapshot_manifest(full)["validation_state"] == "PASS"
    partial = build_golden_snapshot_manifest(_all_state_snapshots()[:3], "v1")
    assert validate_render_golden_snapshot_manifest(partial)["validation_state"] == "BLOCKED"


def test_report_pass_requires_all_conformance_pass():
    snaps = _all_state_snapshots()
    manifest = build_golden_snapshot_manifest(snaps, "v1")
    confs = [compare_render_spec_to_golden_snapshot(
        _render_spec(s, "rs_" + s.lower()), snaps[i])
        for i, s in enumerate(("PASS", "BLOCKED", "REVIEW_REQUIRED", "UNKNOWN"))]
    report = build_golden_snapshot_report(manifest, confs)
    assert report["final_recommendation"] == "PASS"
    assert report["display_contract_locked"] is True
    assert validate_render_golden_snapshot_report(report)["validation_state"] == "PASS"


def test_report_fail_closed_precedence():
    snaps = _all_state_snapshots()
    manifest = build_golden_snapshot_manifest(snaps, "v1")
    good = compare_render_spec_to_golden_snapshot(_render_spec("PASS", "rs_pass"), snaps[0])

    blocked = copy.deepcopy(good)
    blocked["validation_state"] = "BLOCKED"
    unknown = copy.deepcopy(good)
    unknown["validation_state"] = "UNKNOWN"
    review = copy.deepcopy(good)
    review["validation_state"] = "REVIEW_REQUIRED"

    # BLOCKED dominates everything.
    rep = build_golden_snapshot_report(manifest, [good, review, unknown, blocked])
    assert rep["final_recommendation"] == "BLOCKED"
    # UNKNOWN dominates REVIEW_REQUIRED and PASS.
    rep = build_golden_snapshot_report(manifest, [good, review, unknown])
    assert rep["final_recommendation"] == "UNKNOWN"
    # REVIEW_REQUIRED dominates PASS.
    rep = build_golden_snapshot_report(manifest, [good, review])
    assert rep["final_recommendation"] == "REVIEW_REQUIRED"


def test_report_pass_is_not_publish_or_dispatch_ready():
    snaps = _all_state_snapshots()
    manifest = build_golden_snapshot_manifest(snaps, "v1")
    confs = [compare_render_spec_to_golden_snapshot(
        _render_spec(s, "rs_" + s.lower()), snaps[i])
        for i, s in enumerate(("PASS", "BLOCKED", "REVIEW_REQUIRED", "UNKNOWN"))]
    report = build_golden_snapshot_report(manifest, confs)
    assert report["public_ready"] is False
    assert report["live_ready"] is False
    assert report["executable_dispatch"] is False
    assert report["api_gate_required"] is False


