# --- Fixture-driven validation-state coverage ---

@pytest.mark.parametrize("name,spec", sorted(EXPECTED.items()))
def test_fixture_validation_state(name, spec):
    key, expected = spec
    payload = _load(name)
    result = PROVIDER_GATEWAY_DRY_RUN_VALIDATORS[key](payload)
    assert result["validation_state"] == expected, (name, result["reasons"])


