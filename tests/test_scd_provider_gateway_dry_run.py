# --- Helper builds a SAFE, non-executable plan ---

def test_helper_builds_non_executable_call_plan():
    plan = build_provider_gateway_call_plan(_input())
    assert plan["executable"] is False
    assert plan["dry_run_only"] is True
    for flag in FORBIDDEN_FALSE_FLAGS:
        assert plan.get(flag) is False, flag
    assert validate_provider_gateway_call_plan(plan)["validation_state"] == "PASS"


def test_helper_result_never_provider_live_public_ready():
    ci = _input()
    plan = build_provider_gateway_call_plan(ci)
    spend = build_spend_ledger_entry(ci, plan)
    result = build_provider_gateway_dry_run_result(ci, plan, spend)
    assert result["provider_ready"] is False
    assert result["live_ready"] is False
    assert result["public_ready"] is False
    assert result["executable"] is False
    assert result["dry_run_only"] is True
    assert validate_provider_gateway_dry_run_result(result)["validation_state"] == "PASS"


