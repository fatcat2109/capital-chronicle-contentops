# --- Determinism: prompt hash + cache key recomputation ---

def test_prompt_hash_deterministic():
    pack = _canonical()
    first = compute_prompt_hash(pack)
    second = compute_prompt_hash(pack)
    assert first == second
    # Excludes the pack's own prompt_hash field, so reordering it is stable.
    mutated = copy.deepcopy(pack)
    mutated["prompt_hash"] = "sha256:different"
    assert compute_prompt_hash(mutated) == first


def test_prompt_hash_changes_with_body():
    pack = _canonical()
    base = compute_prompt_hash(pack)
    mutated = copy.deepcopy(pack)
    mutated["allowed_angle"] = "a different angle entirely"
    assert compute_prompt_hash(mutated) != base


def test_cache_key_deterministic():
    components = {f: _cache_key()[f] for f in REQUIRED_CACHE_KEY_FIELDS}
    first = compile_prompt_pack_cache_key(components)
    second = compile_prompt_pack_cache_key(components)
    assert first == second
    assert first["composite_key_hash"] == _cache_key()["composite_key_hash"]


def test_cache_key_hash_mismatch_blocks():
    ck = _cache_key()
    ck["composite_key_hash"] = "sha256:tampered"
    assert validate_prompt_pack_cache_key(ck)["validation_state"] == "BLOCKED"


def test_cache_key_missing_component_blocks():
    for field in REQUIRED_CACHE_KEY_FIELDS:
        ck = _cache_key()
        ck.pop("composite_key_hash", None)  # avoid mismatch masking the missing-field block
        ck[field] = ""
        assert validate_prompt_pack_cache_key(ck)["validation_state"] == "BLOCKED", field


