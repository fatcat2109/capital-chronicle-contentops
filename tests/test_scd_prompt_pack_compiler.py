# --- Static guard: no provider / network / env / API imports in the module ---

def test_module_has_no_provider_network_env_imports():
    with open(MODULE_PATH, encoding="utf-8") as fh:
        src = fh.read()
    forbidden = [
        "import requests",
        "import httpx",
        "import urllib",
        "import socket",
        "import openai",
        "import anthropic",
        "subprocess.",
        "os.environ",
        "os.getenv",
        "webbrowser",
    ]
    hits = [tok for tok in forbidden if tok in src]
    assert hits == [], hits
