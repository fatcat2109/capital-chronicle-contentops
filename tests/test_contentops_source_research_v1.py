def independent_writer(research, calls, target="goal20-eia-grid-peaks"):
    main_control = controlled_writer(calls)

    def invoke(**kwargs):
        g = kwargs["governed_input"]
        if "candidates" not in g and g["source_pack"][0].get("report_lineage"):
            return main_control(**kwargs)
        calls.append(kwargs["logical_invocation_id"])
        receipt = {
            "selected_model": "vx/gemini-3.5-flash(high)",
            "total_attempts": 0,
            "replay_only": True,
            "model_identity_provider_verifiable": False,
        }
        if "candidates" in g:
            candidate = next(c for c in g["candidates"] if c["headline_id"] == target)
            return {
                "schema_version": "contentops.v1_simple_gemini_selection.v2",
                "status": "SELECT_CANDIDATE_PLAN",
                "ordered_candidate_plan": [
                    {
                        "candidate_id": candidate["candidate_id"],
                        "article_mode": "DATA_OR_DOCUMENT_LENS",
                        "selection_rationale": "Controlled choice of retained independent official evidence.",
                        "research_queries": [
                            "Examine the official record and its limitations"
                        ],
                    }
                ],
                "selection_summary": "Controlled source-backed output; no fresh model call.",
                "public_write_attempted": False,
            }, receipt
        source = g["source_pack"][0]
        text = research.records[target]["headline_text"]
        grid = "grid" in target
        bls = "bls" in target
        title = (
            "BLS: Consumer Price Index increased in September"
            if bls
            else "EIA: PJM, ERCOT and SWPP set peak load records"
            if grid
            else "EIA: small-scale solar generation grew over the past decade"
        )
        article = {
            "title": title,
            "dek": title + ". The source describes a historical observation.",
            "search_title": title,
            "meta_description": title + ". Read the source, context and limits.",
            "social_hook": title + ". What the dated evidence can and cannot tell us.",
            "substack_body_markdown": ("BLS reports: " if bls else "EIA reports: ")
            + text
            + " [[SOURCE:SOURCE_1]]",
        }
        if grid:
            limitation = 'Data from Form EIA-930 is reported to us by each balancing authority (BA) and is made available "as-is".'
        else:
            limitation = "We do not collect data on the electric power generated by rooftop solar installations, so we estimate small-scale generation using information collected on Form EIA-861."
        if limitation in source["canonical_content_text"]:
            article["substack_body_markdown"] += (
                "\n\nEIA's qualification: " + limitation + " [[SOURCE:SOURCE_1]]"
            )
        claims = [
            {
                "claim_id": "metadata-" + key,
                "claim_text": value,
                "claim_kind": "FACT",
                "source_id": "SOURCE_1",
                "support_excerpt": text,
                "attribution_required": True,
            }
            for key, value in article.items()
            if key != "substack_body_markdown"
        ]
        claims.append(
            {
                "claim_id": "retained-observation",
                "claim_text": text,
                "claim_kind": "FACT",
                "source_id": "SOURCE_1",
                "support_excerpt": text,
                "attribution_required": True,
            }
        )
        if limitation in source["canonical_content_text"]:
            claims.append(
                {
                    "claim_id": "source-limitation",
                    "claim_text": limitation,
                    "claim_kind": "QUOTE",
                    "source_id": "SOURCE_1",
                    "support_excerpt": limitation,
                    "attribution_required": True,
                }
            )
        for context in g["source_pack"][1:]:
            context_text = context["canonical_content_text"]
            article["substack_body_markdown"] += (
                "\n\nSeparate context from EIA: "
                + context_text
                + " [[SOURCE:"
                + context["source_id"]
                + "]]"
            )
            claims.append(
                {
                    "claim_id": "context-" + context["source_id"],
                    "claim_text": context_text,
                    "claim_kind": "FACT",
                    "source_id": context["source_id"],
                    "support_excerpt": context_text,
                    "attribution_required": True,
                }
            )
        return {
            "schema_version": "contentops.v1_simple_gemini_article.v1",
            "article": article,
            "cited_sources": [
                {k: s[k] for k in ("source_id", "url", "publisher", "published_at_utc")}
                for s in g["source_pack"]
            ],
            "material_claim_bindings": claims,
            "public_write_attempted": False,
        }, receipt

    return invoke


def test_real_retained_bytes_and_policy_then_local_tamper(tmp_path):
    research = RetainedSourceResearch(ROOT)
    assert len(research.records) == 3 and not research.gaps
    row = research.headlines(cutoff_utc=NOW)[0]
    assert project_headline(row, cutoff_utc=NOW, locator={})[0] is None
    assert project_headline(
        row, cutoff_utc=NOW, locator={}, permission_resolver=research.permission_for
    )[0]
    assert research.headlines(cutoff_utc="2026-10-18T00:00:00Z") == []
    copied = tmp_path / "research"
    shutil.copytree(ROOT, copied)
    index = json.loads((copied / "index.json").read_bytes())
    target = copied / index["records"][0]["capture_path"]
    target.write_bytes(target.read_bytes() + b"poison")
    broken = RetainedSourceResearch(copied)
    assert len(broken.records) == 2
    assert broken.gaps[0]["state"] == "SOURCE_CAPTURE_HASH_MISMATCH"


@pytest.mark.parametrize("missing_identity", [None, ""])
def test_verified_frozen_record_without_loader_id_reaches_source_pack(missing_identity):
    from live_contentops.v1_simple_gemini_newsroom_v1 import _source_pack

    research = RetainedSourceResearch(ROOT)
    selected, context = list(research.records)[:2]
    for identity in (selected, context):
        research.records[identity]["document"]["document_id"] = missing_identity
    resumed = RetainedSourceResearch.from_frozen_snapshot(research.frozen_snapshot())
    request = {"headline_ids": [selected], "cluster_id": "frozen-record-identity",
               "retained_supporting_headline_ids": [context]}
    evidence = resumed.evidence(request, cutoff_utc=NOW)
    assert evidence["status"] == "PASS"
    pack = _source_pack(evidence["evidence_documents"])
    assert [p["document_id"] for p in pack] == [selected, context]
    assert pack[0]["canonical_content_text"] == research.records[selected]["permitted_source_text"]
    assert evidence["evidence_documents"][1]["context_only"] is True
    assert evidence["provenance"]["request_count_for_call"] == 0
    assert evidence["publication_authority"] is False


def test_mixed_independent_main_recirculation_and_restart(tmp_path):
    f = feed(tmp_path)
    research = RetainedSourceResearch(ROOT)
    f.retained_research = research
    f.poll(cutoff_utc=NOW)
    from live_contentops.contentops_main_headline_projection_v1 import (
        permitted_report_headlines,
    )

    exporter = MainHeadlineExporter(f.tracker.store, research=research)
    first = exporter.export(
        batch_id="independent",
        paths=[],
        cutoff_utc=NOW,
        permitted_rows=permitted_report_headlines(f.tracker),
    )
    assert first["independent_items"] == 3
    assert first["main_origin_recirculated_items"] == 2
    assert exporter.export(batch_id="independent", paths=[], cutoff_utc=NOW) == first
    next_page = exporter.export(
        batch_id="next",
        paths=[],
        cutoff_utc=NOW,
        permitted_rows=permitted_report_headlines(f.tracker),
    )
    assert next_page["eligible_rows"] == 0


def test_independent_candidate_uses_same_simple_and_reuses_output(tmp_path):
    f = feed(tmp_path)
    research = RetainedSourceResearch(ROOT)
    f.retained_research = research
    calls = []
    result = f.opportunity(
        output_dir=tmp_path / "draft",
        cutoff_utc=NOW,
        run_id="independent",
        rolling_input={"headlines": []},
        llm_invoke=independent_writer(research, calls),
    )
    r = result["report_workspace_result"]
    assert r["classification"] == "INDEPENDENT_NEWS_DRAFT", r.get("exact_next_blocker")
    assert (
        r["draft_count"] == 1
        and len(r["previews"]) == 8
        and len(r["media_assets"]) == 2
    )
    assert len(r["evidence"]) == 2
    assert len(calls) == 2 and r["model_execution_state"] == "INJECTED_REPLAY_ONLY"
    repeated = f.opportunity(
        output_dir=tmp_path / "draft",
        cutoff_utc=NOW,
        run_id="independent",
        rolling_input={"headlines": []},
        llm_invoke=lambda **_: (_ for _ in ()).throw(
            AssertionError("duplicate provider")
        ),
    )
    assert (
        repeated["report_workspace_result"]["article_identity"] == r["article_identity"]
    )
    assert len(calls) == 2


